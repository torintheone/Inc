# Короткий английский вариант названия; тексты — по-русски основной язык игры.
EN_TITLES = {e[0]: e[0].replace("_", " ").capitalize() for e in EVENTS}


def rows() -> list[tuple[str, str, str]]:
    out = []
    for eid, title, text, options in EVENTS:
        out.append((f"EVENT_{eid}", title, EN_TITLES[eid]))
        out.append((f"EVENT_{eid}_TEXT", text, EN_TITLES[eid] + ("." if "%s" not in text else ": %s.")))
        for oid, label in options:
            out.append((f"EVENT_{eid}_{oid}", label, oid.replace("_", " ").capitalize()))
    return out
